import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { sassPlugin } from "esbuild-sass-plugin";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// JS 产物：src/main.ts -> main.js
const jsContext = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

// CSS 产物：src/styles/index.scss -> styles.css（Obsidian 会自动加载插件根目录下的 styles.css）
const cssContext = await esbuild.context({
  entryPoints: ["src/styles/index.scss"],
  outfile: "styles.css",
  bundle: true,
  plugins: [sassPlugin()],
  logLevel: "info",
  sourcemap: prod ? false : "inline",
});

if (prod) {
  await Promise.all([jsContext.rebuild(), cssContext.rebuild()]);
  process.exit(0);
} else {
  await Promise.all([jsContext.watch(), cssContext.watch()]);
}
